// Generates shared/api.gen.ts from the backend's UI OpenAPI spec
// (backend/openapi/ui-openapi.json, written by `python -m backend.scripts.export_openapi`).
//
//   npm run gen:api    write shared/api.gen.ts
//   npm run check:api  exit 1 when shared/api.gen.ts is out of date (CI)
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const specUrl = new URL("../../backend/openapi/ui-openapi.json", import.meta.url);
const outUrl = new URL("../shared/api.gen.ts", import.meta.url);
const check = process.argv.includes("--check");

const HEADER = `/**
 * Generated by \`npm run gen:api\` from backend/openapi/ui-openapi.json. Do not edit.
 * Change the backend schema, run \`python -m backend.scripts.export_openapi\`, then
 * \`npm run gen:api\`. Hand-written aliases live next to their domain in shared/*.ts.
 */
`;

const spec = JSON.parse(await readFile(specUrl, "utf8"));
const ast = await openapiTS(spec);
const output = HEADER + "\n" + astToString(ast);

const outPath = fileURLToPath(outUrl);
if (check) {
  let current = null;
  try {
    current = await readFile(outUrl, "utf8");
  } catch {
    current = null;
  }
  if (current !== output) {
    console.error(`${outPath} is out of date. Run \`npm run gen:api\` and commit the result.`);
    process.exit(1);
  }
  console.log("shared/api.gen.ts is up to date.");
} else {
  await writeFile(outUrl, output);
  console.log(`Wrote ${outPath}`);
}
