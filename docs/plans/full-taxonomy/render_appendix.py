"""
Write the two generated appendices of docs/plans/full-taxonomy.md from the packs:

  docs/plans/full-taxonomy/tree.md        every node, by pack, branch and group
  docs/plans/full-taxonomy/crosswalk.md   every legacy leaf and the nodes it maps to

Run from the repo root after any change to etl/taxonomy/:
  etl/.venv/bin/python docs/plans/full-taxonomy/render_appendix.py

It reads YAML files only. It needs no network and no database.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "etl" / "src"))

from etl.domain import taxonomy_pack  # noqa: E402

PACK_TITLES = {"ma": "M&A pack (`ma`)", "tax": "Tax pack (`tax`)"}
SCHEME_TITLES = {
    "section_v1": "Live section tree (`section_v1`, 99 leaves)",
    "section_v2": "140-leaf redesign (`section_v2`)",
    "tax_v1": "Tax clause tree (`tax_v1`, all 150 nodes)",
}
GENERATED = "<!-- Generated by docs/plans/full-taxonomy/render_appendix.py. Do not edit by hand. -->"


def _marks(node: taxonomy_pack.Node) -> str:
    data = node.data
    marks: list[str] = []
    if node.kind != "provision":
        marks.append(node.kind)
    if data.get("wave") == 2:
        marks.append("wave 2")
    schema = data.get("value_schema")
    if isinstance(schema, dict):
        marks.append("value" if schema.get("status") == "piloted" else "value stub")
    attributes = data.get("attributes")
    if isinstance(attributes, dict):
        marks.append(f"party: {attributes['party']}")
    if data.get("parent"):
        marks.append(f"part of `{data['parent']}`")
    if data.get("new_in_redesign"):
        marks.append("**new**")
    listed = data.get("also_listed_under")
    if listed:
        marks.append("also under " + ", ".join(f"`{target}`" for target in listed))
    return "; ".join(marks)


def render_tree(taxonomy: taxonomy_pack.Taxonomy) -> str:
    children: dict[str, list[taxonomy_pack.Node]] = defaultdict(list)
    for node in taxonomy.nodes.values():
        if node.nav_parent:
            children[node.nav_parent].append(node)

    lines = [GENERATED, "", "# Full taxonomy: every node", ""]
    lines.append("Marks: the kind when it is not `provision`; `wave 2` for an M&A concept that the second labeling")
    lines.append("wave covers (every other M&A concept is in wave 1); `value` for a piloted value schema;")
    lines.append("`value stub` for an untested sketch of fields; the party role that an instance records.")
    lines.append("")
    lines.append("In the M&A pack, † after a group name means that the group can be the label of a section in wave 1")
    lines.append("(`assignable: true`): the group holds wave 2 concepts. Every tax navigation node is assignable.")
    for pack in taxonomy_pack.PACKS:
        lines += ["", f"## {PACK_TITLES[pack]}"]
        branches = [node for node in taxonomy.nodes.values() if node.pack == pack and node.kind == "branch"]
        for branch in sorted(branches, key=lambda node: node.data.get("order", 0)):
            proposed = " (**new**)" if branch.data.get("new_in_redesign") else ""
            lines += ["", f"### {branch.label}{proposed}", "", f"`{branch.id}`", ""]
            lines += ["| Group | Id | Label | Marks |", "|---|---|---|---|"]
            direct = [node for node in children[branch.id] if node.is_concept]
            for concept in direct:
                lines.append(f"| (branch) | `{concept.id}` | {concept.label} | {_marks(concept)} |")
            for group in [node for node in children[branch.id] if node.kind == "group"]:
                concepts = children[group.id]
                name = group.label + (" †" if pack == "ma" and group.data.get("assignable") else "")
                if not concepts:
                    lines.append(f"| {name} | `{group.id}` | (no concepts) | |")
                for concept in concepts:
                    lines.append(f"| {name} | `{concept.id}` | {concept.label} | {_marks(concept)} |")

    lines += ["", "## Seam between the packs", ""]
    lines.append("Each node below has one owner pack and is also listed under a navigation node of the other pack.")
    lines += ["", "| Owner | Node | Label | Also listed under |", "|---|---|---|---|"]
    for node in taxonomy.nodes.values():
        other = [target for target in node.data.get("also_listed_under") or [] if not target.startswith(node.pack + ".")]
        if other:
            targets = ", ".join(f"`{target}`" for target in other)
            lines.append(f"| {node.pack} | `{node.id}` | {node.label} | {targets} |")
    return "\n".join(lines) + "\n"


def render_crosswalk(taxonomy: taxonomy_pack.Taxonomy) -> str:
    links: dict[str, dict[str, list[str]]] = {scheme: defaultdict(list) for scheme in taxonomy_pack.LEGACY_SCHEMES}
    for node in taxonomy.nodes.values():
        crosswalk = node.data.get("crosswalk") or {}
        for scheme, entries in crosswalk.items():
            for entry in entries:
                party = f", {entry['party']}" if entry.get("party") else ""
                links[scheme][entry["id"]].append(f"`{node.id}` ({entry['relation']}{party})")

    lines = [GENERATED, "", "# Full taxonomy: crosswalk from the older trees", ""]
    lines.append("The relation describes the new node compared with the older node.")
    lines.append("`narrower` means that the older node was split. `broader` means that older nodes were merged.")
    for scheme in taxonomy_pack.LEGACY_SCHEMES:
        rows = taxonomy.legacy[scheme]
        lines += ["", f"## {SCHEME_TITLES[scheme]}", "", "| Older id | Older label | New node(s) |", "|---|---|---|"]
        for legacy_id, row in rows.items():
            if scheme != "tax_v1" and not row.get("leaf"):
                continue
            label = str(row.get("label") or "").replace("|", "/")
            lines.append(f"| `{legacy_id}` | {label} | {'; '.join(links[scheme][legacy_id]) or '(none)'} |")

    new_ids = [
        node.id
        for node in taxonomy.nodes.values()
        if node.pack == "ma" and node.is_concept and not node.data.get("crosswalk")
    ]
    lines += ["", f"## M&A concepts with no older leaf ({len(new_ids)})", ""]
    lines.append("These concepts are new. No leaf of either older section tree has the same or a wider scope.")
    lines.append("")
    lines += [f"- `{node_id}`: {taxonomy.nodes[node_id].label}" for node_id in new_ids]
    return "\n".join(lines) + "\n"


def main() -> int:
    taxonomy = taxonomy_pack.load()
    errors = taxonomy_pack.validate(taxonomy)
    if errors:
        print(f"The packs are not valid ({len(errors)} problems). Fix them first.", file=sys.stderr)
        return 1
    (HERE / "tree.md").write_text(render_tree(taxonomy), encoding="utf-8")
    (HERE / "crosswalk.md").write_text(render_crosswalk(taxonomy), encoding="utf-8")
    print("wrote tree.md and crosswalk.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
